from transformers import AutoTokenizer, AutoModelForSequenceClassification
import torch

model_name = "cybersectony/phishing-email-detection-distilbert_v2.4.1"

tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSequenceClassification.from_pretrained(model_name)

print("Model loaded successfully!")
print(model.config.id2label)

def predict_email(email_text):
    inputs = tokenizer(
        email_text,
        return_tensors="pt",
        truncation=True,
        max_length=512
    )

    with torch.no_grad():
        outputs = model(**inputs)
        probabilities = torch.softmax(outputs.logits, dim=-1)[0]

    labels = model.config.id2label

    results = {
        labels.get(i, str(i)): prob.item()
        for i, prob in enumerate(probabilities)
    }

    prediction = max(results, key=results.get)

    return {
        "prediction": prediction,
        "confidence": results[prediction],
        "all_probabilities": results
    }

print("Prediction function is ready!")

email = """
Dear User,
Your account security needs immediate attention.
Please verify your credentials.
Click here: http://suspicious-link.com
"""

result = predict_email(email)

print("Prediction:", result["prediction"])
print(f"Confidence: {result['confidence']:.2%}")

print("\nAll probabilities:")
for label, prob in result["all_probabilities"].items():
    print(f"{label}: {prob:.2%}")

print("Model labels:", model.config.id2label)
print("Number of labels:", model.config.num_labels)